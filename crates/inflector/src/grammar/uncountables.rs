/// Checks whether a lowercase word is in the standard English uncountable nouns dictionary.
pub fn is_uncountable(word_lower: &str) -> bool {
    UNCOUNTABLE_NOUNS.binary_search(&word_lower).is_ok()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn test_is_uncountable() {
        assert!(is_uncountable("money"));
        assert!(is_uncountable("rice"));
        assert!(is_uncountable("information"));
        assert!(is_uncountable("equipment"));
        assert!(is_uncountable("series"));
        assert!(is_uncountable("species"));
        assert!(is_uncountable("yoga"));

        assert!(!is_uncountable("user"));
        assert!(!is_uncountable("category"));
        assert!(!is_uncountable("box"));
    }

    #[test]
    fn test_uncountables_sorted() {
        for window in UNCOUNTABLE_NOUNS.windows(2) {
            assert!(
                window[0] < window[1],
                "UNCOUNTABLE_NOUNS is not sorted: '{}' >= '{}'",
                window[0],
                window[1]
            );
        }
    }
}
