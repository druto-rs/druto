//! Zero-dependency Latin diacritic and accent transliteration to ASCII.

/// Maps accented characters and diacritics to their ASCII equivalents.
pub(crate) fn transliterate_char(character: char) -> Option<&'static str> {
    match character {
        'à' | 'á' | 'â' | 'ã' | 'ä' | 'å' | 'ā' | 'ă' | 'ą' => Some("a"),
        'À' | 'Á' | 'Â' | 'Ã' | 'Ä' | 'Å' | 'Ā' | 'Ă' | 'Ą' => Some("A"),
        'æ' => Some("ae"),
        'Æ' => Some("AE"),
        'ç' | 'ć' | 'ĉ' | 'ċ' | 'č' => Some("c"),
        'Ç' | 'Ć' | 'Ĉ' | 'Ċ' | 'Č' => Some("C"),
        'đ' | 'ð' => Some("d"),
        'Đ' | 'Ð' => Some("D"),
        'è' | 'é' | 'ê' | 'ë' | 'ē' | 'ĕ' | 'ė' | 'ę' | 'ě' => Some("e"),
        'È' | 'É' | 'Ê' | 'Ë' | 'Ē' | 'Ĕ' | 'Ė' | 'Ę' | 'Ě' => Some("E"),
        'ì' | 'í' | 'î' | 'ï' | 'ĩ' | 'ī' | 'ĭ' | 'į' | 'ı' => Some("i"),
        'Ì' | 'Í' | 'Î' | 'Ï' | 'Ĩ' | 'Ī' | 'Ĭ' | 'Į' | 'İ' => Some("I"),
        'ł' => Some("l"),
        'Ł' => Some("L"),
        'ñ' | 'ń' | 'ņ' | 'ň' => Some("n"),
        'Ñ' | 'Ń' | 'Ņ' | 'Ň' => Some("N"),
        'ò' | 'ó' | 'ô' | 'õ' | 'ö' | 'ø' | 'ō' | 'ŏ' | 'ő' => Some("o"),
        'Ò' | 'Ó' | 'Ô' | 'Õ' | 'Ö' | 'Ø' | 'Ō' | 'Ŏ' | 'Ő' => Some("O"),
        'œ' => Some("oe"),
        'Œ' => Some("OE"),
        'ś' | 'ŝ' | 'ş' | 'š' => Some("s"),
        'Ś' | 'Ŝ' | 'Ş' | 'Š' => Some("S"),
        'ß' => Some("ss"),
        'ť' | 'ţ' => Some("t"),
        'Ť' | 'Ţ' => Some("T"),
        'þ' => Some("th"),
        'Þ' => Some("TH"),
        'ù' | 'ú' | 'û' | 'ü' | 'ũ' | 'ū' | 'ŭ' | 'ů' | 'ű' | 'ų' => Some("u"),
        'Ù' | 'Ú' | 'Û' | 'Ü' | 'Ũ' | 'Ū' | 'Ŭ' | 'Ů' | 'Ű' | 'Ų' => Some("U"),
        'ý' | 'ÿ' | 'ŷ' => Some("y"),
        'Ý' | 'Ŷ' | 'Ÿ' => Some("Y"),
        'ź' | 'ż' | 'ž' => Some("z"),
        'Ź' | 'Ż' | 'Ž' => Some("Z"),
        _ => None,
    }
}
